#!/usr/bin/env bash
#
# Rebuild inventory/hosts.ini from the running Vagrant machines.
#
# The inventory hostnames are the private network IP addresses on purpose: the
# role uses `ansible_host` as the kubelet node IP, and delegates the
# `kubeadm token create` call to `kubernetes_control_plane_ip`, which therefore
# has to be an inventory host.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

declare -A MACHINE_IP=(
  [control-server1]=192.168.56.6
  [control-server2]=192.168.56.7
  [worker-server]=192.168.56.8
)

declare -A MACHINE_GROUP=(
  [control-server1]=primary_control_plane
  [control-server2]=secondary_control_plane
  [worker-server]=node
)

ssh_field() {
  # $1 = ssh-config block, $2 = ssh_config keyword
  awk -v key="$2" 'tolower($1) == tolower(key) { print $2; exit }' <<<"$1"
}

ssh_fields() {
  # $1 = ssh-config block, $2 = ssh_config keyword, all the values
  awk -v key="$2" 'tolower($1) == tolower(key) { print $2 }' <<<"$1"
}

pick_key() {
  # $1 = ssh-config block. `vagrant ssh-config` advertises several IdentityFile
  # entries (vagrant.key.ed25519 then vagrant.key.rsa) and lets ssh try them in
  # order, but only the one packaged in the box authorized_keys authenticates.
  # Ansible accepts a single key, so probe them and keep the one that works.
  local config=$1 host port user key
  host=$(ssh_field "$config" HostName)
  port=$(ssh_field "$config" Port)
  user=$(ssh_field "$config" User)

  while read -r key; do
    key=${key//\"/}
    [[ -n "$key" && -r "$key" ]] || continue
    if ssh -i "$key" -o IdentitiesOnly=yes -o BatchMode=yes \
           -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
           -o ConnectTimeout=10 -o LogLevel=ERROR \
           -p "$port" "$user@$host" true 2>/dev/null; then
      printf '%s' "$key"
      return 0
    fi
  done < <(ssh_fields "$config" IdentityFile)

  return 1
}

declare -A GROUP_LINES=()

for machine in control-server1 control-server2 worker-server; do
  if ! config=$(vagrant ssh-config "$machine" 2>/dev/null); then
    echo "error: '$machine' is not running, start it with 'vagrant up'" >&2
    exit 1
  fi

  user=$(ssh_field "$config" User)

  if [[ -z "$user" ]]; then
    echo "error: could not read the ssh settings of '$machine'" >&2
    exit 1
  fi

  if ! key=$(pick_key "$config"); then
    echo "error: none of the ssh keys of '$machine' authenticates, try 'vagrant reload $machine'" >&2
    exit 1
  fi

  group=${MACHINE_GROUP[$machine]}
  GROUP_LINES[$group]+="${MACHINE_IP[$machine]} ansible_user=${user} ansible_ssh_private_key_file=${key}"$'\n'
done

{
  echo "# Generated by bin/gen-inventory.sh, do not edit by hand."
  for group in primary_control_plane secondary_control_plane node; do
    echo
    echo "[$group]"
    printf '%s' "${GROUP_LINES[$group]}"
  done
  echo
  echo "[k8s_cluster:children]"
  echo "primary_control_plane"
  echo "secondary_control_plane"
  echo "node"
} >inventory/hosts.ini

# With `config.ssh.insert_key = false`, the key resolved above is the Vagrant
# insecure private key packaged in the box, in practice the RSA one
# (~/.vagrant.d/insecure_private_keys/vagrant.key.rsa).

echo "inventory/hosts.ini written:"
cat inventory/hosts.ini
